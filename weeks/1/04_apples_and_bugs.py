"""
本关任务：你买了一箱n个苹果，很不幸的是买完时箱子里混进了一条虫子。虫子每x小时能吃掉一个苹果，假设虫子在吃完一个苹果之前不会吃另一个，那么经过y小时你还有多少个完整的苹果？

不允许使用分支语句，建议使用数学库函数ceil和内置函数max等
注意：需要考虑苹果被吃光的情况，也就是y > x * n的可能

测试输入：
10
4
9

预期输出：
7
"""

import math

n = int(input(''))  # 输入苹果的总数
x = int(input(''))  # 输入虫子吃苹果的速度
y = int(input(''))  # 输入虫子吃苹果的总时间

# 开始补充代码，格式必须和样例一致

apples_left = max(0, math.floor(n - y / x))
print(apples_left)